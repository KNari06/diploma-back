import { supabaseAdmin } from '@/db/supabase';
import { TestPlan } from '@/services/testing/plans/test-plan-generator.service';
import { FinalTestReport, PlaywrightCommand, TestResult } from '@/types';
import { logger } from '@/utils/core/logger';

/**
 * Service for generating comprehensive test reports with code, artifacts, and analysis
 */
export class TestReportGeneratorService {
  /**
   * Ownership-aware report retrieval (safe helper for API layers)
   * Returns null if test does not exist OR does not belong to user (prevents enumeration).
   */
  static async getReportByTestIdForUser(testId: string, userId: string): Promise<FinalTestReport | null> {
    try {
      const { data, error } = await supabaseAdmin
        .from('tests')
        .select('id')
        .eq('id', testId)
        .eq('user_id', userId)
        .single();

      if (error || !data) return null;
      return await this.getReportByTestId(testId);
    } catch {
      return null;
    }
  }

  /**
   * Generate final test report with all artifacts and generated code
   */
  static async generateFinalReport(params: {
    testId: string;
    testResult: TestResult;
    testPlan?: TestPlan;
    aiAnalysis?: any;
  }): Promise<FinalTestReport> {
    const { testId, testResult, testPlan, aiAnalysis } = params;

    logger.info('[REPORT_GENERATOR] Generating final report', {
      testId,
      status: testResult.status,
      hasTestPlan: !!testPlan,
      hasAIAnalysis: !!aiAnalysis,
    });

    try {
      // ✅ FIX #1: Get test URL from database (testResult doesn't have url field)
      let testUrl = testPlan?.url || '';
      if (!testUrl) {
        const { data: test, error: testError } = await supabaseAdmin
          .from('tests')
          .select('url')
          .eq('id', testId)
          .single();

        if (testError || !test) {
          logger.warn('[REPORT_GENERATOR] Failed to get test URL, using fallback', {
            error: testError?.message,
            testId,
          });
          testUrl = 'URL_NOT_AVAILABLE';
        } else {
          testUrl = test.url;
        }
      }

      // 1. Generate Playwright code from test plan or test result
      const generatedCode = testPlan
        ? this.generatePlaywrightCode(testPlan)
        : this.generateCodeFromTestResult(testResult);

      // 2. Collect all artifacts
      const artifacts = {
        video: testResult.videoUrl,
        trace: testResult.traceUrl,
        screenshots: testResult.screenshot ? [testResult.screenshot] : [],
        dom: testResult.dom,
        logs: testResult.logs || [],
        networkLogs: testResult.networkLogs || [],
      };

      // 3. Format AI analysis
      const analysis = this.formatAIAnalysis(aiAnalysis, testResult);

      // 4. Calculate summary stats
      const summary = this.calculateSummary(testResult, testPlan, analysis);

      // 5. Build report
      const report: FinalTestReport = {
        testId,
        testUrl, // ✅ FIX #1: Use actual URL from DB or testPlan
        status: testResult.status,
        executedAt: testResult.completedAt?.toISOString() || new Date().toISOString(),
        duration: this.calculateDuration(testResult),

        generatedCode,
        artifacts,
        analysis,
        summary,
      };

      // 6. Save report to database
      await this.saveFinalReport(report);

      logger.info('[REPORT_GENERATOR] Final report generated successfully', {
        testId,
        bugsFound: summary.bugsFound,
        criticalBugs: summary.criticalBugs,
      });

      return report;
    } catch (error) {
      logger.error('[REPORT_GENERATOR] Failed to generate report', {
        error: error instanceof Error ? error.message : String(error),
        testId,
      });
      throw error;
    }
  }

  /**
   * Generate Playwright test code from test plan
   */
  private static generatePlaywrightCode(testPlan: TestPlan): FinalTestReport['generatedCode'] {
    const commands = testPlan.commands || [];
    const steps = testPlan.steps || [];

    let code = `import { test, expect } from '@playwright/test';\n\n`;
    code += `test.describe('${testPlan.summary || 'Generated test'}', () => {\n`;
    code += `  test('${testPlan.scope || 'general'} test', async ({ page }) => {\n`;
    code += `    // Test URL: ${testPlan.url}\n`;
    code += `    // Generated by QAI on ${new Date().toISOString()}\n\n`;

    for (const command of commands) {
      code += this.generateCommandCode(command);
    }

    code += `  });\n`;
    code += `});\n`;

    return {
      language: 'typescript',
      framework: 'playwright',
      code,
      steps: steps.map((s: any) => s.description || s.action),
      commands,
    };
  }

  /**
   * Generate code for a single Playwright command
   */
  private static generateCommandCode(command: PlaywrightCommand): string {
    const indent = '    ';
    let code = '';

    // Add description as comment
    if (command.description) {
      code += `${indent}// ${command.description}\n`;
    }

    switch (command.action) {
      case 'goto':
        code += `${indent}await page.goto('${command.url}');\n`;
        break;

      case 'click':
        if (command.selector) {
          code += `${indent}await page.click('${command.selector}');\n`;
        }
        break;

      case 'fill':
        if (command.selector && command.value) {
          code += `${indent}await page.fill('${command.selector}', '${command.value}');\n`;
        }
        break;

      case 'type':
        if (command.selector && command.value) {
          code += `${indent}await page.type('${command.selector}', '${command.value}');\n`;
        }
        break;

      case 'select':
        if (command.selector && command.value) {
          code += `${indent}await page.selectOption('${command.selector}', '${command.value}');\n`;
        }
        break;

      case 'check':
        if (command.selector) {
          code += `${indent}await page.check('${command.selector}');\n`;
        }
        break;

      case 'uncheck':
        if (command.selector) {
          code += `${indent}await page.uncheck('${command.selector}');\n`;
        }
        break;

      case 'hover':
        if (command.selector) {
          code += `${indent}await page.hover('${command.selector}');\n`;
        }
        break;

      case 'press':
        if (command.value) {
          code += `${indent}await page.keyboard.press('${command.value}');\n`;
        }
        break;

      case 'wait':
        if (command.timeout) {
          code += `${indent}await page.waitForTimeout(${command.timeout});\n`;
        } else if (command.selector) {
          code += `${indent}await page.waitForSelector('${command.selector}');\n`;
        }
        break;

      case 'waitForNavigation':
        code += `${indent}await page.waitForNavigation();\n`;
        break;

      case 'screenshot': {
        const filename = command.selector || `screenshot-${Date.now()}.png`;
        code += `${indent}await page.screenshot({ path: '${filename}' });\n`;
        break;
      }

      case 'assert':
        if (command.selector) {
          code += `${indent}await expect(page.locator('${command.selector}')).toBeVisible();\n`;
        }
        break;

      case 'extract':
        if (command.selector) {
          code += `${indent}const extracted = await page.locator('${command.selector}').textContent();\n`;
          code += `${indent}console.log('Extracted:', extracted);\n`;
        }
        break;

      default:
        code += `${indent}// ${command.action}: ${command.description || 'No description'}\n`;
    }

    code += '\n';
    return code;
  }

  /**
   * Generate code from test result (fallback when no test plan)
   */
  private static generateCodeFromTestResult(testResult: TestResult): FinalTestReport['generatedCode'] {
    let code = `import { test, expect } from '@playwright/test';\n\n`;
    code += `test('Generated from test result', async ({ page }) => {\n`;
    code += `  // This test was executed without explicit commands\n`;
    code += `  // Test ID: ${testResult.testId}\n`;
    code += `  // Status: ${testResult.status}\n`;
    code += `  \n`;
    code += `  await page.goto('URL_HERE');\n`;
    code += `  \n`;
    code += `  // Add your test steps here\n`;
    code += `  await page.screenshot({ path: 'screenshot.png' });\n`;
    code += `});\n`;

    return {
      language: 'typescript',
      framework: 'playwright',
      code,
      steps: ['Navigate to URL', 'Take screenshot'],
      commands: [],
    };
  }

  /**
   * Format AI analysis for report
   */
  private static formatAIAnalysis(
    aiAnalysis: any,
    testResult: TestResult
  ): FinalTestReport['analysis'] {
    const bugs: FinalTestReport['analysis']['bugs'] = [];

    // Extract bugs from AI analysis
    if (aiAnalysis?.bugs && Array.isArray(aiAnalysis.bugs)) {
      for (const bug of aiAnalysis.bugs) {
        bugs.push({
          severity: bug.severity || 'medium',
          type: bug.type || 'unknown',
          message: bug.message || bug.description || 'No description',
          selector: bug.selector,
          recommendation: bug.recommendation || bug.fix || 'No recommendation',
        });
      }
    }

    // Extract bugs from test errors
    if (testResult.errors && testResult.errors.length > 0) {
      for (const error of testResult.errors) {
        bugs.push({
          severity: error.type === 'javascript' ? 'high' : 'medium',
          type: error.type,
          message: error.message,
          selector: undefined,
          recommendation: 'Fix the error in the code',
        });
      }
    }

    // Determine overall severity
    const hasCritical = bugs.some(b => b.severity === 'critical');
    const hasHigh = bugs.some(b => b.severity === 'high');
    const hasMedium = bugs.some(b => b.severity === 'medium');

    const severity = hasCritical ? 'critical' : hasHigh ? 'high' : hasMedium ? 'medium' : bugs.length > 0 ? 'low' : 'none';

    return {
      bugs,
      severity,
      recommendations: aiAnalysis?.recommendations || [],
      confidence: aiAnalysis?.confidence || 0.8,
    };
  }

  /**
   * Calculate summary statistics
   */
  private static calculateSummary(
    testResult: TestResult,
    testPlan: TestPlan | undefined,
    analysis: FinalTestReport['analysis']
  ): FinalTestReport['summary'] {
    const totalSteps = testPlan?.steps?.length || testPlan?.commands?.length || 1;
    const failedSteps = testResult.errors?.length || 0;
    const passedSteps = Math.max(0, totalSteps - failedSteps);

    return {
      totalSteps,
      passedSteps,
      failedSteps,
      bugsFound: analysis.bugs.length,
      criticalBugs: analysis.bugs.filter(b => b.severity === 'critical').length,
    };
  }

  /**
   * Calculate test duration in milliseconds
   */
  private static calculateDuration(testResult: TestResult): number {
    if (testResult.completedAt && testResult.createdAt) {
      return new Date(testResult.completedAt).getTime() - new Date(testResult.createdAt).getTime();
    }
    return 0;
  }

  /**
   * Save final report to database
   * Note: test_reports table may not exist yet - this is optional functionality
   */
  private static async saveFinalReport(report: FinalTestReport): Promise<void> {
    try {
      // Check if test_reports table exists before attempting insert
      const { error } = await supabaseAdmin
        .from('test_reports')
        .insert({
          test_id: report.testId,
          test_url: report.testUrl,
          status: report.status,
          executed_at: report.executedAt,
          duration: report.duration,
          generated_code: report.generatedCode,
          artifacts: report.artifacts,
          analysis: report.analysis,
          summary: report.summary,
          created_at: new Date().toISOString(),
        });

      if (error) {
        // PGRST205 = table not found (expected if migration not applied yet)
        if (error.code === 'PGRST205') {
          logger.debug('[REPORT_GENERATOR] test_reports table not available (migration pending)', {
            testId: report.testId,
          });
        } else {
          logger.error('[REPORT_GENERATOR] Failed to save report to DB', {
            error,
            testId: report.testId,
          });
        }
        // Don't throw - report generation is still successful
      } else {
        logger.info('[REPORT_GENERATOR] Report saved to database', {
          testId: report.testId,
        });
      }
    } catch (error) {
      logger.debug('[REPORT_GENERATOR] Report save skipped (table may not exist)', {
        testId: report.testId,
      });
      // Don't throw - report generation is still successful
    }
  }

  /**
   * Get existing report by test ID
   * Note: test_reports table may not exist yet - this is optional functionality
   */
  static async getReportByTestId(testId: string): Promise<FinalTestReport | null> {
    try {
      const { data, error } = await supabaseAdmin
        .from('test_reports')
        .select('*')
        .eq('test_id', testId)
        .single();

      if (error) {
        // PGRST205 = table not found (expected if migration not applied yet)
        if (error.code === 'PGRST205') {
          logger.debug('[REPORT_GENERATOR] test_reports table not available', { testId });
        } else {
          logger.debug('[REPORT_GENERATOR] Report not found', { testId });
        }
        return null;
      }

      if (!data) {
        return null;
      }

      return {
        testId: data.test_id,
        testUrl: data.test_url,
        status: data.status,
        executedAt: data.executed_at,
        duration: data.duration,
        generatedCode: data.generated_code,
        artifacts: data.artifacts,
        analysis: data.analysis,
        summary: data.summary,
      };
    } catch (error) {
      logger.debug('[REPORT_GENERATOR] Report query skipped', { testId });
      return null;
    }
  }
}
