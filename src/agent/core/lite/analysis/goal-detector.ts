  /**
   * Final auditor validation using gpt-4o
   * Called when heuristic claims goal is done to confirm or reject
   * Uses stronger model for higher accuracy ("decides fate of the test")
   *
   * @param context - Full goal context
   * @param lastAction - Description of the last action taken
   * @returns AuditorResult with isDone/isBlocked/reason
   */
  async auditDone(
    context: GoalContext,
    lastAction?: string
  ): Promise<AuditorResult> {
    const prompt = `You are a Senior QA Auditor validating test completion.

GOAL: ${context.goal}
CURRENT URL: ${context.page.url}
PAGE TITLE: ${context.page.title}

PAGE CONTENT SUMMARY (key elements):
${context.snapshotSummary.slice(0, 40).join('\n') || 'No elements'}

LAST ACTION: ${lastAction || context.lastOutcome || 'Unknown'}

TASK: Based on the page state, determine if:
1. The goal has been FULLY achieved (isDone)
2. The test is BLOCKED by something requiring user help (captcha, 2FA, verification code)

Look for:
- Success messages ("Thank you", "Confirmed", "Welcome")
- Error messages ("Invalid", "Error", "Failed")
- Blocking elements (CAPTCHA, SMS code input, 2FA prompt)
- Expected page state for the goal

Respond with JSON ONLY:
{
  "isDone": true|false,
  "confidence": 0.0-1.0,
  "reason": "Brief explanation",
  "nextStepIfMissing": "What is still missing? (only if isDone=false)",
  "isBlocked": true|false,
  "blockedReason": "Why blocked? (only if isBlocked=true)",
  "canUserHelp": true|false
}

Be STRICT - only set isDone=true if there is clear success evidence.
Set isBlocked=true ONLY for hard blocks (captcha, 2FA, phone verification).`;

    logger.info('[GOAL_DETECTOR] Calling auditor (gpt-4o)', {
      testId: this.testId,
      goal: context.goal.slice(0, 50),
      url: context.page.url,
    });

    try {
      const response = await LitePromptBuilder.askJson<{
        isDone?: boolean;
        confidence?: number;
        reason?: string;
        nextStepIfMissing?: string;
        isBlocked?: boolean;
        blockedReason?: string;
        canUserHelp?: boolean;
      }>(prompt, {
        model: 'gpt-4o', // Higher accuracy model for final validation
        temperature: 0.1,
        maxTokens: 500,
        timeoutMs: 15000,
      });

      if (!response) {
        logger.warn('[GOAL_DETECTOR] Auditor timed out or failed', {
          testId: this.testId,
        });
        // Conservative: reject the done claim
        return {
          isDone: false,
          confidence: 0,
          reason: 'Auditor failed to respond',
          isBlocked: false,
        };
      }

      const result: AuditorResult = {
        isDone: response.isDone ?? false,
        confidence: Math.max(0, Math.min(1, response.confidence ?? 0)),
        reason: response.reason || 'No reason provided',
        nextStepIfMissing: response.nextStepIfMissing,
        isBlocked: response.isBlocked ?? false,
        blockedReason: response.blockedReason,
        canUserHelp: response.canUserHelp ?? false,
      };

      logger.info('[GOAL_DETECTOR] Auditor result', {
        testId: this.testId,
        isDone: result.isDone,
        confidence: result.confidence.toFixed(2),
        isBlocked: result.isBlocked,
        reason: result.reason.slice(0, 80),
      });

      return result;
    } catch (error) {
      // Check if cancelled
      if (error instanceof Error && error.message.includes('cancelled')) {
        throw error;
      }

      logger.error('[GOAL_DETECTOR] Auditor error', {
        testId: this.testId,
        error: error instanceof Error ? error.message : String(error),
      });

      // Conservative: reject the done claim on error
      return {
        isDone: false,
        confidence: 0,
        reason: `Auditor error: ${error instanceof Error ? error.message : 'Unknown'}`,
        isBlocked: false,
      };
    }
  }

  /**
   * Parse snapshot summary back into minimal elements
   * Format: "tag[type]:name"
   */
  private parseSnapshotSummary(summary: string[]): Array<{
    ref: string;
    role: string;
    name: string;
    tag: string;
    type?: string;
    visible: boolean;
  }> {
    return summary.map((entry, idx) => {
      // Parse "tag[type]:name" or "tag:name"
      const match = entry.match(/^(\w+)(?:\[([^\]]+)\])?:(.+)$/);
      if (!match) {
        return {
          ref: `e${idx}`,
          role: 'generic',
          name: entry,
          tag: 'span',
          visible: true,
        };
      }

      const [, tag, type, name] = match;
      return {
        ref: `e${idx}`,
        role: this.tagToRole(tag),
        name: name.trim(),
        tag: tag.toLowerCase(),
        type: type || undefined,
        visible: true,
      };
    });
  }

  /**
   * Map tag to ARIA role (simplified)
   */
  private tagToRole(tag: string): string {
    const roleMap: Record<string, string> = {
      button: 'button',
      a: 'link',
      input: 'textbox',
      textarea: 'textbox',
      select: 'combobox',
      h1: 'heading',
      h2: 'heading',
      h3: 'heading',
      form: 'form',
    };
    return roleMap[tag.toLowerCase()] || 'generic';
  }
