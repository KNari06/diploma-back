/**
 * TaskPlanBuilder
 * Generates a high-level task plan (list of target states) for autonomous navigation.
 * Uses gemini-2.5-flash-lite to create state-transition based plan, not action-based.
 *
 * Key principles:
 * - Plans describe SUCCESS SIGNALS (expected states), not actions
 * - Each step has URL patterns, required text, and success elements
 * - Lightweight plan refinement for stuck recovery (max 1-2 times per test)
 */

import { logger } from '@/utils/core/logger';
import type { LiteSnapshot } from '../lite-types';
import { LitePromptBuilder } from '../prompt/lite-prompt-builder';
import { AI_TASK_MODELS } from '@/config/ai/ai-models.config';

/**
 * Expected state for a plan step
 */
export interface ExpectedState {
  /** Regex pattern for URL (e.g., "/search|/category") */
  url_regex: string;
  /** Required text on page (headlines, labels) */
  required_text: string[];
  /** CSS selectors for success elements */
  success_elements: string[];
  /** Optional elements (may or may not be present) */
  optional_elements?: string[];
}

/**
 * Single step in the task plan
 */
export interface TaskPlanStep {
  /** Unique step ID (e.g., "step_1") */
  id: string;
  /** Human-readable goal for this step */
  goal: string;
  /** Expected state when step is completed */
  expected_state: ExpectedState;
  /** Signals that indicate failure (e.g., "no results", "404") */
  fail_signals: string[];
}

/**
 * Complete task plan
 */
export interface TaskPlan {
  /** List of steps to reach the goal */
  steps: TaskPlanStep[];
  /** Original goal */
  originalGoal: string;
  /** Whether this plan was generated by AI */
  isAIGenerated: boolean;
  /** Timestamp when plan was created */
  createdAt: number;
  /** Number of refinements done */
  refineCount: number;
}

/**
 * Current position in the plan
 */
export interface PlanPosition {
  /** Current step index (0-based) */
  currentStepIndex: number;
  /** Current step */
  currentStep: TaskPlanStep;
  /** Next step (if any) */
  nextStep?: TaskPlanStep;
  /** Whether we're on the last step */
  isLastStep: boolean;
  /** Last known good URL (for rollback) */
  lastKnownGoodUrl?: string;
}

/**
 * TaskPlanBuilder
 * Creates and manages task plans for autonomous agent navigation
 */
export class TaskPlanBuilder {
  private testId: string;
  private goal: string;
  private plan: TaskPlan | null = null;

  /** Maximum refinements allowed per test */
  private static readonly MAX_REFINES = 2;

  /** Maximum steps in a plan */
  private static readonly MAX_STEPS = 8;

  constructor(goal: string, testId: string) {
    this.goal = goal;
    this.testId = testId;
  }

  /**
   * Generate initial task plan using AI
   * Called once at the start of the test
   *
   * @param startUrl - Starting URL
   * @param snapshotSummary - Summary of initial page state
   * @returns TaskPlan or null if generation failed
   */
  async generatePlan(startUrl: string, snapshotSummary: string[]): Promise<TaskPlan | null> {
    logger.info('[TASK_PLAN_BUILDER] Generating initial plan', {
      testId: this.testId,
      goal: this.goal.slice(0, 80),
      startUrl,
    });

    const prompt = this.buildGenerationPrompt(startUrl, snapshotSummary);

    try {
      const response = await LitePromptBuilder.askJson<{
        steps: Array<{
          id: string;
          goal: string;
          expected_state: {
            url_regex: string;
            required_text: string[];
            success_elements: string[];
            optional_elements?: string[];
          };
          fail_signals: string[];
        }>;
      }>(prompt, {
        model: AI_TASK_MODELS.taskPlanning,
        temperature: 0.2,
        maxTokens: 1200,
        timeoutMs: 15000,
      });

      if (!response || !response.steps || response.steps.length === 0) {
        logger.warn('[TASK_PLAN_BUILDER] AI returned empty plan, using fallback', {
          testId: this.testId,
        });
        return this.buildFallbackPlan();
      }

      // Validate and limit steps
      const validatedSteps = response.steps
        .slice(0, TaskPlanBuilder.MAX_STEPS)
        .map((step, index) => ({
          id: step.id || `step_${index + 1}`,
          goal: step.goal || `Step ${index + 1}`,
          expected_state: {
            url_regex: step.expected_state?.url_regex || '.*',
            required_text: step.expected_state?.required_text?.slice(0, 5) || [],
            success_elements: step.expected_state?.success_elements?.slice(0, 5) || [],
            optional_elements: step.expected_state?.optional_elements?.slice(0, 3) || [],
          },
          fail_signals: step.fail_signals?.slice(0, 5) || ['error', '404'],
        }));

      this.plan = {
        steps: validatedSteps,
        originalGoal: this.goal,
        isAIGenerated: true,
        createdAt: Date.now(),
        refineCount: 0,
      };

      logger.info('[TASK_PLAN_BUILDER] Plan generated successfully', {
        testId: this.testId,
        stepsCount: this.plan.steps.length,
        stepIds: this.plan.steps.map(s => s.id),
      });

      return this.plan;
    } catch (error) {
      logger.error('[TASK_PLAN_BUILDER] Plan generation failed', {
        testId: this.testId,
        error: error instanceof Error ? error.message : String(error),
      });
      return this.buildFallbackPlan();
    }
  }

  /**
   * Refine plan when stuck
   * Only updates current and next step (not entire plan)
   * Limited to MAX_REFINES per test
   *
   * @param currentStepIndex - Index of current (stuck) step
   * @param currentSnapshot - Current page snapshot
   * @param stuckReason - Why we're stuck
   * @returns Updated plan or null if refinement not possible
   */
  async refinePlan(
    currentStepIndex: number,
    currentSnapshot: LiteSnapshot,
    stuckReason: string
  ): Promise<TaskPlan | null> {
    if (!this.plan) {
      logger.warn('[TASK_PLAN_BUILDER] Cannot refine: no plan exists');
      return null;
    }

    if (this.plan.refineCount >= TaskPlanBuilder.MAX_REFINES) {
      logger.warn('[TASK_PLAN_BUILDER] Max refinements reached', {
        testId: this.testId,
        refineCount: this.plan.refineCount,
        max: TaskPlanBuilder.MAX_REFINES,
      });
      return null;
    }

    logger.info('[TASK_PLAN_BUILDER] Refining plan for stuck step', {
      testId: this.testId,
      stuckStepIndex: currentStepIndex,
      stuckReason,
      refineCount: this.plan.refineCount,
    });

    const prompt = this.buildRefinePrompt(currentStepIndex, currentSnapshot, stuckReason);

    try {
      const response = await LitePromptBuilder.askJson<{
        current_step: TaskPlanStep;
        next_step?: TaskPlanStep;
      }>(prompt, {
        model: AI_TASK_MODELS.taskPlanning,
        temperature: 0.3,
        maxTokens: 800,
        timeoutMs: 12000,
      });

      if (!response || !response.current_step) {
        logger.warn('[TASK_PLAN_BUILDER] Refine failed: empty response');
        return null;
      }

      // Update current step
      if (currentStepIndex < this.plan.steps.length) {
        this.plan.steps[currentStepIndex] = {
          ...response.current_step,
          id: this.plan.steps[currentStepIndex].id, // Keep original ID
        };
      }

      // Update next step if provided
      if (response.next_step && currentStepIndex + 1 < this.plan.steps.length) {
        this.plan.steps[currentStepIndex + 1] = {
          ...response.next_step,
          id: this.plan.steps[currentStepIndex + 1].id,
        };
      }

      this.plan.refineCount++;

      logger.info('[TASK_PLAN_BUILDER] Plan refined successfully', {
        testId: this.testId,
        refineCount: this.plan.refineCount,
        updatedStepId: this.plan.steps[currentStepIndex].id,
      });

      return this.plan;
    } catch (error) {
      logger.error('[TASK_PLAN_BUILDER] Plan refinement failed', {
        testId: this.testId,
        error: error instanceof Error ? error.message : String(error),
      });
      return null;
    }
  }

  /**
   * Get current plan
   */
  getPlan(): TaskPlan | null {
    return this.plan;
  }

  /**
   * Get position in plan for given step index
   */
  getPosition(stepIndex: number): PlanPosition | null {
    if (!this.plan || stepIndex < 0 || stepIndex >= this.plan.steps.length) {
      return null;
    }

    return {
      currentStepIndex: stepIndex,
      currentStep: this.plan.steps[stepIndex],
      nextStep: stepIndex + 1 < this.plan.steps.length ? this.plan.steps[stepIndex + 1] : undefined,
      isLastStep: stepIndex === this.plan.steps.length - 1,
    };
  }

  /**
   * Build prompt for initial plan generation
   */
  private buildGenerationPrompt(startUrl: string, snapshotSummary: string[]): string {
    return `You are a QA Strategy Expert. Create a step-by-step plan to achieve the user's goal.

GOAL: "${this.goal}"
START URL: ${startUrl}
VISIBLE ELEMENTS: ${snapshotSummary.slice(0, 20).join(', ')}

IMPORTANT RULES:
1. Describe SUCCESS SIGNALS (expected states), NOT actions.
   - BAD: "Click the login button"
   - GOOD: "Login form is visible with email and password fields"

2. Each step MUST have url_regex for reliable context detection.

3. Use success_elements with CSS selectors for key elements.

4. Keep fail_signals focused on real errors (not just missing content).

5. Maximum 5-8 steps. Simpler is better.

Respond with JSON only:
{
  "steps": [
    {
      "id": "step_1",
      "goal": "Brief description of what should happen",
      "expected_state": {
        "url_regex": "pattern to match URL (e.g., '/login|/signin')",
        "required_text": ["text that should be visible"],
        "success_elements": ["CSS selectors for key elements"],
        "optional_elements": ["elements that may or may not appear"]
      },
      "fail_signals": ["error messages or failure indicators"]
    }
  ]
}`;
  }

  /**
   * Build prompt for plan refinement
   */
  private buildRefinePrompt(
    currentStepIndex: number,
    currentSnapshot: LiteSnapshot,
    stuckReason: string
  ): string {
    const currentStep = this.plan!.steps[currentStepIndex];
    const nextStep = this.plan!.steps[currentStepIndex + 1];

    const snapshotSummary = currentSnapshot.elements
      .slice(0, 15)
      .map(el => `${el.tag}[${el.role}]: ${el.name || el.placeholder || el.value || ''}`.slice(0, 60))
      .join('\n');

    return `You are a QA Expert. The test is stuck on step ${currentStepIndex + 1}.

GOAL: "${this.goal}"
CURRENT URL: ${currentSnapshot.url}
STUCK REASON: ${stuckReason}

CURRENT STEP (stuck):
${JSON.stringify(currentStep, null, 2)}

${nextStep ? `NEXT STEP:\n${JSON.stringify(nextStep, null, 2)}` : ''}

CURRENT PAGE STATE:
${snapshotSummary}

Your task: Update ONLY the current step (and optionally next step) to help overcome this obstacle.
Do NOT rewrite the entire plan. Focus on alternative success signals or adjusted expectations.

Respond with JSON:
{
  "current_step": { ... updated step ... },
  "next_step": { ... updated next step (optional) ... }
}`;
  }

  /**
   * Build fallback plan when AI fails
   */
  private buildFallbackPlan(): TaskPlan {
    logger.info('[TASK_PLAN_BUILDER] Building fallback plan', {
      testId: this.testId,
    });

    // Simple 2-step fallback: navigate + complete goal
    this.plan = {
      steps: [
        {
          id: 'step_1',
          goal: 'Navigate to target page',
          expected_state: {
            url_regex: '.*',
            required_text: [],
            success_elements: [],
            optional_elements: [],
          },
          fail_signals: ['error', '404', '500'],
        },
        {
          id: 'step_2',
          goal: this.goal,
          expected_state: {
            url_regex: '.*',
            required_text: [],
            success_elements: [],
            optional_elements: [],
          },
          fail_signals: ['error', 'failed'],
        },
      ],
      originalGoal: this.goal,
      isAIGenerated: false,
      createdAt: Date.now(),
      refineCount: 0,
    };

    return this.plan;
  }
}
