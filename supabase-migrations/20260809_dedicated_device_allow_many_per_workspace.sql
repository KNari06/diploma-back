-- Воркспейс может иметь НЕСКОЛЬКО закреплённых устройств.
--
-- ЗАЧЕМ. С одним закреплённым эмулятором клиент не может запустить регресс,
-- пока кто-то сидит в редакторе: устройство одно, второй заход отбивается
-- DEVICE_BUSY. Это не редкость, а норма рабочего дня — у JanaPost именно так
-- и получилось (регресс TC-01 показывал 5 красных из 8 прогонов и метку
-- «25% flaky», хотя тест был исправен, просто устройство было занято).
--
-- ЧТО СНИМАЕТСЯ. Ровно ограничение «один воркспейс — одна строка». Обратное
-- ограничение остаётся и оно важнее: uniq_dedicated_device_target не даёт
-- ОДНОМУ устройству обслуживать два воркспейса, иначе два клиента снова
-- окажутся в одном Android /data. То есть «много устройств одному клиенту»
-- разрешаем, «одно устройство двум клиентам» — по-прежнему нет.
--
-- ⚠️ ЭТУ МИГРАЦИЮ НЕЛЬЗЯ ПРИМЕНЯТЬ БЕЗ КОДА, КОТОРЫЙ С НЕЙ ЕДЕТ.
-- Прежний резолвер читает строку через `.maybeSingle()`, а он возвращает
-- ОШИБКУ, когда строк больше одной. db-слой эту ошибку проглатывает и отдаёт
-- null — то есть воркспейс с двумя устройствами МОЛЧА уехал бы в общий пул,
-- потеряв изоляцию. Уникальность здесь работала ещё и как страховка от такого
-- чтения; снимая её, обязаны заменить чтение на списочное.
--
-- Индекс по workspace_id (idx_workspace_dedicated_device_workspace_id) уже
-- есть и остаётся — теперь он несёт настоящую нагрузку, а не дублирует
-- уникальный.

SET search_path TO public;

ALTER TABLE workspace_dedicated_device
  DROP CONSTRAINT IF EXISTS workspace_dedicated_device_workspace_id_key;

COMMENT ON COLUMN workspace_dedicated_device.workspace_id IS
  'Воркспейс. НЕ уникален: одному воркспейсу можно закрепить несколько устройств (параллельные прогоны). Обратное запрещено индексом uniq_dedicated_device_target.';
